import { afterEach, beforeEach, expect, it } from "bun:test"
import {
  mkdtemp,
  mkdir,
  readFile,
  readdir,
  rm,
  writeFile,
} from "node:fs/promises"
import { tmpdir } from "node:os"
import { join, resolve } from "node:path"

const command = process.env.NOODLE_TEST_BINARY
  ? [resolve(process.env.NOODLE_TEST_BINARY)]
  : [process.execPath, resolve("src/app/cli.ts")]
const fixture = resolve("tests/fixtures/fastapi-3.1.json")
let dir: string
beforeEach(async () => {
  dir = await mkdtemp(join(tmpdir(), "noodle-openapi31-"))
})
afterEach(async () => {
  await rm(dir, { recursive: true, force: true })
})

async function cli(...args: string[]) {
  const child = Bun.spawn([...command, ...args, "--json"], {
    cwd: dir,
    env: { ...process.env, HOME: dir, USERPROFILE: dir, XDG_CONFIG_HOME: dir },
    stdout: "pipe",
    stderr: "pipe",
  })
  const [stdout, stderr, code] = await Promise.all([
    new Response(child.stdout).text(),
    new Response(child.stderr).text(),
    child.exited,
  ])
  const output = JSON.parse(stdout)
  return { output, code, stderr }
}

it("imports a generated FastAPI document and sends the path, query, body and auth to a loopback server", async () => {
  // Fixture generated by FastAPI 0.142.2 and Pydantic 2.13.5 via app.openapi().
  const calls: {
    path: string
    method: string
    auth: string | null
    body: string
  }[] = []
  const server = Bun.serve({
    hostname: "127.0.0.1",
    port: 0,
    async fetch(request) {
      const url = new URL(request.url)
      calls.push({
        path: url.pathname + url.search,
        method: request.method,
        auth: request.headers.get("authorization"),
        body: await request.text(),
      })
      return Response.json({ ok: true })
    },
  })
  try {
    const root = join(dir, "inventory")
    const imported = await cli("import", fixture, "-o", dir)
    expect(imported.output).toMatchObject({
      status: "success",
      data: { path: root },
    })
    expect(imported.output.data.warnings).toBeUndefined()
    expect(
      (await cli("collection", "inspect", root)).output.data.requestCount,
    ).toBe(2)
    expect(
      await readFile(join(root, ".environments/default.env"), "utf8"),
    ).toContain("base_url=\n")
    expect(calls).toHaveLength(0)
    for (const [key, value] of [
      ["base_url", server.url.origin],
      ["token", "test-bearer"],
    ] as const) {
      expect(
        (
          await cli(
            "environment",
            "set",
            key,
            value,
            "--env",
            "default",
            "--collection",
            root,
          )
        ).output.status,
      ).toBe("success")
    }
    const result = await cli(
      "collection",
      "run",
      root,
      "--env",
      "default",
      "--noproxy",
    )
    expect(result.output).toMatchObject({ status: "success", errors: [] })
    expect(result.code).toBe(0)
    expect(
      calls.map(({ path, method, auth }) => ({ path, method, auth })),
    ).toEqual([
      { path: "/items/7?limit=10", method: "GET", auth: null },
      { path: "/orders", method: "POST", auth: "Bearer test-bearer" },
    ])
    expect(JSON.parse(calls[1]!.body)).toEqual({ items: [{ name: "pencil" }] })
  } finally {
    server.stop(true)
  }
}, 15000)

it("reports external references without fetching them and fails empty documents before touching the destination", async () => {
  let fetched = 0
  const server = Bun.serve({
    hostname: "127.0.0.1",
    port: 0,
    fetch() {
      fetched++
      return Response.json({ example: "private-value" })
    },
  })
  try {
    const spec = join(dir, "api.yml")
    await writeFile(join(dir, "private-value.yml"), "example: private-value\n")
    await writeFile(
      spec,
      `openapi: 3.1.0
info: { title: Inventory }
paths:
  /pets:
    post:
      parameters: [{ $ref: '${server.url.origin}/private-value' }]
      requestBody: { $ref: './private-value.yml' }
`,
    )
    const result = await cli("import", spec, "--format", "openapi", "-o", dir)
    expect(result.output).toMatchObject({
      status: "success",
      data: {
        warnings: [
          { field: "parameters", itemPath: ["POST /pets"] },
          { field: "requestBody", itemPath: ["POST /pets"] },
        ],
      },
    })
    expect(JSON.stringify(result.output)).not.toContain("private-value")
    expect(fetched).toBe(0)
    const existing = join(dir, "inventory")
    const files = await readdir(existing)
    const saved = await readFile(join(existing, "post-pets.yml"))
    await writeFile(
      spec,
      "openapi: 3.1.0\ninfo: { title: Inventory }\nwebhooks: { incoming: { post: {} } }",
    )
    const invalid = await cli("import", spec, "-o", dir)
    expect(invalid.code).not.toBe(0)
    expect(invalid.output.errors.join(" ")).toContain(
      "no supported path operations",
    )
    expect(await readdir(existing)).toEqual(files)
    expect(await readFile(join(existing, "post-pets.yml"))).toEqual(saved)
  } finally {
    server.stop(true)
  }
})

it("restores an existing collection after a late settings failure", async () => {
  const root = join(dir, "inventory")
  await mkdir(join(root, "items"), { recursive: true })
  await writeFile(
    join(root, "items", "get-items-item-id.yml"),
    "# Keep my original bytes\n",
  )
  await writeFile(
    join(root, "settings.yml"),
    "hooks: { setup: missing-request }\n",
  )
  const result = await cli("import", fixture, "-o", dir)
  expect(result.code).not.toBe(0)
  expect((await readdir(root)).sort()).toEqual(["items", "settings.yml"])
  expect(await readdir(join(root, "items"))).toEqual(["get-items-item-id.yml"])
  expect(
    await readFile(join(root, "items", "get-items-item-id.yml"), "utf8"),
  ).toBe("# Keep my original bytes\n")
})
